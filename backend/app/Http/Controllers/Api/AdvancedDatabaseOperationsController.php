    /**
     * Q10: Transaction Procedure - sp_CreateBookingWithPayment
     */
    public function createBookingTransaction(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'traveler_id' => 'required|integer',
            'package_id' => 'required|integer',
            'travel_date' => 'required|date',
            'travelers' => 'required|integer|min:1|max:20',
            'amount' => 'required|numeric|min:1',
        ]);

        $results = DB::select('CALL sp_CreateBookingWithPayment(?, ?, ?, ?, ?)', [
            $validated['traveler_id'],
            $validated['package_id'],
            $validated['travel_date'],
            $validated['travelers'],
            $validated['amount'],
        ]);

        $latestBooking = DB::table('bookings')->orderBy('booking_id', 'desc')->first();
        $latestPayment = DB::table('payments')->orderBy('payment_id', 'desc')->first();

        return response()->json([
            'success' => true,
            'question' => 'Q10',
            'title' => 'sp_CreateBookingWithPayment (TRANSACTION + SAVEPOINT + HANDLERS)',
            'result' => $results,
            'booking' => $latestBooking,
            'payment' => $latestPayment
        ]);
    }

