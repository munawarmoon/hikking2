    /**
     * Q9 Tester: Modify package price or status to test trigger live
     */
    public function testTriggerPriceUpdate(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'package_id' => 'required|integer',
            'new_price' => 'required|numeric|min:1',
            'new_status' => 'nullable|string|in:draft,published,archived'
        ]);

        $pkgId = $validated['package_id'];
        $newPrice = $validated['new_price'];
        $newStatus = $validated['new_status'] ?? null;

        $oldPackage = DB::table('packages')->where('id', $pkgId)->first();

        if (!$oldPackage) {
            return response()->json([
                'success' => false,
                'message' => 'Package not found'
            ], 404);
        }

        $updateData = ['price' => $newPrice];
        if ($newStatus) {
            $updateData['status'] = $newStatus;
        }

        DB::table('packages')->where('id', $pkgId)->update($updateData);

        // Fetch latest audit record for this package
        $latestAudit = DB::table('package_audit')
            ->where('package_id', $pkgId)
            ->orderBy('id', 'desc')
            ->first();

        return response()->json([
            'success' => true,
            'message' => 'Package updated successfully. Trigger fired and logged to package_audit!',
            'old_values' => [
                'price' => $oldPackage->price,
                'status' => $oldPackage->status
            ],
            'audit_entry' => $latestAudit
        ]);
    }

